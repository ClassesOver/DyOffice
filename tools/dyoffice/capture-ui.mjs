import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
const require=createRequire('/tmp/dyoffice-capture/package.json');
const {chromium}=require('playwright');
const JSZip=require('jszip');
await mkdir('screenshots',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:3080',{waitUntil:'networkidle'});
await page.getByRole('heading',{name:'dyoffice',exact:true}).waitFor();
await page.screenshot({path:'screenshots/01-login.png',fullPage:true});
await page.getByLabel('访问令牌').fill(process.env.DYOFFICE_USER_TOKEN);
await page.getByRole('button',{name:'登录',exact:true}).click();
await page.getByRole('button',{name:'我的文件',exact:true}).waitFor();
await page.getByText('暂无文件，导入文档开始使用。',{exact:true}).waitFor();
await page.screenshot({path:'screenshots/02-workspace.png',fullPage:true});
await page.getByRole('button',{name:'个人偏好',exact:true}).click();
await page.getByRole('heading',{name:'个人偏好',exact:true}).waitFor();
await page.getByLabel('界面主题').waitFor();
await page.getByRole('button',{name:'保存偏好',exact:true}).waitFor();
await page.screenshot({path:'screenshots/03-preferences.png',fullPage:true});
await page.getByRole('button',{name:'我的文件',exact:true}).click();
await page.getByRole('button',{name:'导入文件',exact:true}).waitFor();
const zip=new JSZip();
zip.file('[Content_Types].xml','<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>');
zip.file('_rels/.rels','<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>');
zip.file('word/document.xml','<?xml version="1.0" encoding="UTF-8"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>DyOffice 界面演示</w:t></w:r></w:p><w:p><w:r><w:t>这是用于截图的测试文档，不包含真实用户数据。</w:t></w:r></w:p><w:p><w:r><w:t>当前开发版可编辑 DOCX 正文段落，并保存和下载原生文档。</w:t></w:r></w:p><w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr></w:body></w:document>');
await page.locator('input[type=file]').setInputFiles({name:'DyOffice界面演示.docx',mimeType:'application/vnd.openxmlformats-officedocument.wordprocessingml.document',buffer:await zip.generateAsync({type:'nodebuffer'})});
await page.getByRole('button',{name:'编辑',exact:true}).waitFor();
await page.getByRole('button',{name:'编辑',exact:true}).click();
await page.locator('textarea').first().waitFor();
if(!(await page.locator('textarea').first().inputValue()).includes('DyOffice')) throw Error('Document text did not load');
await page.screenshot({path:'screenshots/04-docx-editor.png',fullPage:true});
await writeFile('screenshots/provenance.json',JSON.stringify({baseCommit:'f8d0d816e283fae74de380937e38a9dff2439c63',capturedCommit:process.env.GITHUB_SHA,viewport:{width:1440,height:1000},browser:'Chromium via Playwright',data:'Fresh empty local development workspace; no mock API or fabricated UI',errors},null,2));
await browser.close();
if(errors.length) throw Error(errors.join('; '));
