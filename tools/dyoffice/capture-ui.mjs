import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
const require=createRequire('/tmp/dyoffice-capture/package.json');
const {chromium}=require('playwright');
await mkdir('screenshots',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:3080',{waitUntil:'networkidle'});
await page.getByRole('heading',{name:'dyoffice',exact:true}).waitFor();
await page.screenshot({path:'screenshots/01-login.png',fullPage:true});
await page.getByLabel('访问令牌').fill(process.env.DYOFFICE_USER_TOKEN);
await page.getByRole('button',{name:'登录',exact:true}).click();
await page.getByRole('button',{name:'我的文件',exact:true}).waitFor();
await page.screenshot({path:'screenshots/02-workspace.png',fullPage:true});
await page.getByRole('button',{name:'个人偏好',exact:true}).click();
await page.getByRole('heading',{name:'个人偏好',exact:true}).waitFor();
await page.screenshot({path:'screenshots/03-preferences.png',fullPage:true});
await writeFile('screenshots/provenance.json',JSON.stringify({baseCommit:'f8d0d816e283fae74de380937e38a9dff2439c63',capturedCommit:process.env.GITHUB_SHA,viewport:{width:1440,height:1000},browser:'Chromium via Playwright',data:'Fresh empty local development workspace; no mock API or fabricated UI',errors},null,2));
await browser.close();
if(errors.length) throw Error(errors.join('; '));
