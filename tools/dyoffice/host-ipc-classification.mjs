// T00: classify every editor preload bridge member for the Web host.
//
//   node tools/dyoffice/host-ipc-classification.mjs --check   # fail on drift
//   node tools/dyoffice/host-ipc-classification.mjs --write   # regenerate host-ipc.md
//
// Rules in docs/dyoffice/inventory/host-ipc-classification.json are matched in
// order against `app/bridge.member` ids from tools/audit-web-host.mjs; the first
// match wins. --check fails when a member is unclassified, a rule matches
// nothing (stale), a rule names an unknown class, or host-ipc.md is out of date.
import { readFile, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { auditWebHost, inventoryRows } from '../audit-web-host.mjs'

const root = fileURLToPath(new URL('../../', import.meta.url))
const RULES_PATH = 'docs/dyoffice/inventory/host-ipc-classification.json'
const DOC_PATH = 'docs/dyoffice/inventory/host-ipc.md'
export const CLASSES = Object.freeze(['browser-native', 'server-api', 'isolated-worker', 'unsupported', 'desktop-only'])
const TASK = /^T\d{2}$/

export function validateRules(spec) {
  const problems = []
  if (spec?.schema !== 1) problems.push('schema must be 1')
  if (!Array.isArray(spec?.rules) || !spec.rules.length) return [...problems, 'rules must be a non-empty array']
  for (const c of CLASSES) if (typeof spec.classes?.[c] !== 'string') problems.push('missing class definition: ' + c)
  const ids = new Set()
  for (const [i, rule] of spec.rules.entries()) {
    const at = 'rule ' + (rule?.id ?? '#' + i)
    if (typeof rule?.id !== 'string' || !/^[a-z0-9-]+$/.test(rule.id)) problems.push(at + ': id must be kebab-case')
    else if (ids.has(rule.id)) problems.push(at + ': duplicate id')
    else ids.add(rule.id)
    if (!CLASSES.includes(rule?.class)) problems.push(at + ': unknown class ' + JSON.stringify(rule?.class))
    if (!TASK.test(rule?.verifyIn ?? '')) problems.push(at + ': verifyIn must name a plan task (Txx)')
    for (const field of ['web', 'rationale']) if (typeof rule?.[field] !== 'string' || rule[field].length < 8) problems.push(at + ': ' + field + ' is required')
    try { new RegExp(rule?.match) } catch { problems.push(at + ': invalid match pattern') }
  }
  return problems
}

/** Assign each row its first matching rule; report unclassified rows and unused rules. */
export function classify(rows, spec) {
  const rules = spec.rules.map((r) => ({ ...r, re: new RegExp(r.match) }))
  const used = new Map(rules.map((r) => [r.id, 0]))
  const classified = []
  const unclassified = []
  for (const row of rows) {
    const rule = rules.find((r) => r.re.test(row.id))
    if (!rule) { unclassified.push(row.id); continue }
    used.set(rule.id, used.get(rule.id) + 1)
    classified.push({ ...row, class: rule.class, rule: rule.id, verifyIn: rule.verifyIn })
  }
  const unusedRules = [...used].filter(([, n]) => n === 0).map(([id]) => id)
  return { classified, unclassified, unusedRules }
}

const cell = (s) => String(s).replaceAll('|', '\\|').replaceAll('\n', ' ')
// GFM unescapes \| inside table cells before code spans; backticks would end the span
const code = (s) => '`' + cell(s).replaceAll('`', "'") + '`'
const channels = (row) => row.ipc.map((u) => (u.channel === null ? cell(u.op) : cell(u.op) + ' ' + code(u.channel))).join('<br>') || '—'

export function renderMarkdown(result, spec, browserMethods = {}) {
  const { classified } = result
  const apps = [...new Set(classified.map((r) => r.app))]
  const count = (pred) => classified.filter(pred).length
  const lines = [
    '# DyOffice Web host IPC classification (T00)',
    '',
    '> Generated by `node tools/dyoffice/host-ipc-classification.mjs --write` from',
    '> [host-ipc-classification.json](host-ipc-classification.json) and the AST inventory in',
    '> `tools/audit-web-host.mjs`. Do not edit by hand; CI runs `--check`.',
    '',
    '**Status: ' + spec.status + '.** ' + spec.statusNote,
    '',
    '## Classes',
    '',
    '| Class | Meaning |',
    '| --- | --- |',
    ...CLASSES.map((c) => '| `' + c + '` | ' + cell(spec.classes[c]) + ' |'),
    '',
    '## Totals',
    '',
    '| App | ' + CLASSES.map((c) => '`' + c + '`').join(' | ') + ' | Total |',
    '| --- | ' + CLASSES.map(() => '---:').join(' | ') + ' | ---: |',
    ...apps.map((a) => '| ' + a + ' | ' + CLASSES.map((c) => count((r) => r.app === a && r.class === c)).join(' | ') + ' | ' + count((r) => r.app === a) + ' |'),
    '| **all** | ' + CLASSES.map((c) => count((r) => r.class === c)).join(' | ') + ' | ' + classified.length + ' |',
    '',
    'Lifecycle is derived from the IPC operations the preload member performs:',
    '`request` (invoke/sendSync), `subscription` (main→renderer events, returns an',
    'unsubscribe), `notify` (fire-and-forget send) or `local` (no IPC). "Calls" counts',
    'renderer call sites resolved by symbol, including shared workspace packages.',
    '',
    '## Rules',
    '',
    '| Rule | Class | Members | Verify in | Web seam | Rationale |',
    '| --- | --- | ---: | --- | --- | --- |',
    ...spec.rules.map((r) => '| `' + r.id + '` | `' + r.class + '` | ' + count((x) => x.rule === r.id) + ' | ' + r.verifyIn + ' | ' + cell(r.web) + ' | ' + cell(r.rationale) + ' |'),
  ]
  for (const app of apps) {
    lines.push('', '## ' + app, '', '| Member | Lifecycle | IPC | Calls | Class | Rule |', '| --- | --- | --- | ---: | --- | --- |')
    for (const r of classified.filter((x) => x.app === app)) {
      lines.push('| `' + r.bridge + '.' + r.name + '` | ' + r.lifecycle + ' | ' + channels(r) + ' | ' + r.calls + ' | `' + r.class + '` | `' + r.rule + '` |')
    }
  }
  const browserRows = Object.entries(browserMethods).flatMap(([app, methods]) =>
    methods.map(method => '| ' + app + ' | ' + code(method) + ' |'))
  if (browserRows.length) {
    lines.push('', '## Browser-only renderer APIs', '',
      'The Web host supplies these optional members from the shared renderer interfaces.', '',
      '| Editor | Optional member |', '| --- | --- |', ...browserRows)
  }
  return lines.join('\n') + '\n'
}

export async function build(base = root) {
  const spec = JSON.parse(await readFile(join(base, RULES_PATH), 'utf8'))
  const problems = validateRules(spec)
  if (problems.length) return { problems }
  const report = await auditWebHost(base)
  const result = classify(inventoryRows(report), spec)
  for (const id of result.unclassified) problems.push('unclassified member: ' + id)
  for (const id of result.unusedRules) problems.push('rule matches no member (stale): ' + id)
  for (const [app, r] of Object.entries(report)) {
    for (const m of r.unknownRendererMethods) problems.push(app + ': renderer calls undeclared member ' + m)
    for (const o of r.opaqueReferences) problems.push(app + ': unresolved bridge reference at ' + o.file + ':' + o.line)
    for (const b of r.bridges) for (const u of b.unresolved) problems.push(app + ': unresolved preload member in ' + b.name + ': ' + u)
  }
  const browserMethods = Object.fromEntries(Object.entries(report).map(([app, item]) => [app, item.browserOnlyRendererMethods]))
  return { problems, markdown: renderMarkdown(result, spec, browserMethods), result }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const write = process.argv.includes('--write')
  const { problems, markdown, result } = await build()
  if (problems.length) {
    for (const p of problems) console.error('host-ipc: ' + p)
    process.exit(1)
  }
  const docPath = join(root, DOC_PATH)
  if (write) {
    await writeFile(docPath, markdown)
    console.log('wrote ' + DOC_PATH + ' (' + result.classified.length + ' members)')
  } else {
    let current = ''
    try { current = await readFile(docPath, 'utf8') } catch { /* missing counts as drift */ }
    if (current !== markdown) {
      console.error('host-ipc: ' + DOC_PATH + ' is out of date; run with --write and review the diff')
      process.exit(1)
    }
    console.log('host-ipc: ' + result.classified.length + ' members classified, document up to date')
  }
}
