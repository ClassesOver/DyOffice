import type {AgentSkill,AgentToolDef} from '@genoffice/agent-core'

type ImageSearchReply={images:Array<{imageUrl:string;title?:string;width?:number;height?:number}>;method?:string;error?:string}
type GenerateReply={url?:string;error?:string}
export type PdfMediaDependencies={
 imageSearch?:(query:string,maxResults:number,signal?:AbortSignal)=>Promise<ImageSearchReply>
 generateImage?:(input:{prompt:string;aspectRatio?:string},signal?:AbortSignal)=>Promise<GenerateReply>
}
const ASPECT_RATIOS=['1:1','4:3','16:9','9:16','3:4','2:3','3:2','auto']
const SEARCH_TOOL:AgentToolDef={name:'image_search',description:'Search for images and return numbered direct imageUrl links. Choose one and pass its URL to insert_image. Search does not change the PDF.',inputSchema:{type:'object',additionalProperties:false,properties:{query:{type:'string',minLength:1,maxLength:300},max_results:{type:'integer',minimum:1,maximum:8,default:8}},required:['query']}}
const GENERATE_TOOL:AgentToolDef={name:'generate_image',description:'Generate an illustration or diagram and return its image URL for insert_image. Generation does not insert the image or change the PDF.',inputSchema:{type:'object',additionalProperties:false,properties:{prompt:{type:'string',minLength:1,maxLength:4000},aspect_ratio:{type:'string',enum:ASPECT_RATIOS}},required:['prompt']}}
function plainInput(value:unknown,keys:readonly string[]):value is Record<string,unknown>{
 if(!value||typeof value!=='object'||Array.isArray(value)||![Object.prototype,null].includes(Object.getPrototypeOf(value)))return false
 return Reflect.ownKeys(value).every(key=>{const d=Object.getOwnPropertyDescriptor(value,key);return typeof key==='string'&&keys.includes(key)&&!!d?.enumerable&&'value'in d})
}
function text(value:unknown,max:number):value is string{return typeof value==='string'&&!!value.trim()&&value.length<=max&&!/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/.test(value)}
function imageUrl(value:unknown):value is string{
 if(typeof value!=='string'||value.length>8192||/[\u0000-\u0020\u007f]/.test(value))return false
 try{const url=new URL(value);return ['https:','http:'].includes(url.protocol)&&!!url.hostname&&!url.username&&!url.password}catch{return false}
}
/** Dependency adapters retain generated bytes; model output contains only insertable HTTP URLs. */
export function createPdfMediaSkill(dependencies:PdfMediaDependencies):AgentSkill{
 return {
  id:'pdf-media',
  systemPrompt:'Use image_search for photos and generate_image for illustrations when needed and offered. Pass the returned URL to insert_image or replace_image as appropriate; searching and generating do not edit the PDF.',
  tools:[...(dependencies.imageSearch?[SEARCH_TOOL]:[]),...(dependencies.generateImage?[GENERATE_TOOL]:[])],
  async executeTool(call,signal){
   signal?.throwIfAborted()
   const search=call.name==='image_search',generate=call.name==='generate_image',summary=search?'Search images':'Generate image'
   const failure=(output:string)=>({output,summary,isError:true as const,mutated:false})
   if(!search&&!generate||search&&!dependencies.imageSearch||generate&&!dependencies.generateImage)return failure('The requested PDF media tool is unavailable.')
   const input=call.input
   if(search){
    if(!plainInput(input,['query','max_results'])||!text(input.query,300)||input.max_results!==undefined&&(!Number.isSafeInteger(input.max_results)||(input.max_results as number)<1||(input.max_results as number)>8))return failure('Invalid image search request. Supply query and optional max_results from 1 to 8.')
    const maxResults=input.max_results===undefined?8:input.max_results as number
    try{
     const result=await dependencies.imageSearch!(input.query.trim(),maxResults,signal)
     signal?.throwIfAborted()
     if(!result||result.error||result.method==='error'||!Array.isArray(result.images)||result.images.some(image=>!image||!imageUrl(image.imageUrl)))return failure('Image search failed. No image choices are confirmed; retry the search before choosing an image.')
     const images=result.images.slice(0,maxResults)
     const output=images.map((image,index)=>{
      const title=typeof image.title==='string'?image.title.replace(/[\r\n\t]/g,' ').slice(0,300):'(untitled)'
      const dimension=(value:unknown)=>typeof value==='number'&&Number.isFinite(value)&&value>0?String(value):'?'
      return `${index+1}. ${title||'(untitled)'} [${dimension(image.width)}x${dimension(image.height)}]\n   ${image.imageUrl}`
     }).join('\n')
     return {output:output||'(no images found)',summary,mutated:false}
    }catch{signal?.throwIfAborted();return failure('Image search failed. No image choices are confirmed; retry the search before choosing an image.')}
   }
   if(!plainInput(input,['prompt','aspect_ratio'])||!text(input.prompt,4000)||input.aspect_ratio!==undefined&&(typeof input.aspect_ratio!=='string'||!ASPECT_RATIOS.includes(input.aspect_ratio)))return failure('Invalid image generation request. Supply prompt and an offered aspect_ratio.')
   try{
    const result=await dependencies.generateImage!({prompt:input.prompt.trim(),...(input.aspect_ratio!==undefined?{aspectRatio:input.aspect_ratio as string}:{})},signal)
    signal?.throwIfAborted()
    if(!result||result.error||!imageUrl(result.url))return failure('Image generation failed. No usable image URL was returned.')
    return {output:`Generated image URL: ${result.url}\nUse insert_image with this URL to place it in the PDF.`,summary,mutated:false}
   }catch{signal?.throwIfAborted();return failure('Image generation failed. No usable image URL was returned.')}
  },
 }
}
