// Private, one-command IPC entry. Only the registered PDF actions can run;
// file paths, application credentials and revision authority are never passed.
process.once('message',async message=>{
 try{
  const command=JSON.parse(message?.raw)
  let job
  if(command?.action==='applyOpsQuery')job=(await import('./apply-ops-query-job.mjs')).createPdfApplyOpsQueryJob()
  else if(command?.action==='applyOps')job=(await import('./apply-ops-job.mjs')).createPdfApplyOpsJob()
  else if(['imageInsertsQuery','draftInserts','draftInsertsQuery'].includes(command?.action))job=(await import('./draft-inserts-job.mjs')).createPdfDraftInsertsJob(command.action)
  else if(command?.action==='annotationsQuery')job=(await import('./annotations-query-job.mjs')).createPdfAnnotationsQueryJob()
  else if(command?.action==='textEditsQuery')job=(await import('./text-edits-query.mjs')).createPdfTextEditsQueryJob()
  else if(command?.action==='imagePreviewQuery')job=(await import('./image-preview-query.mjs')).createPdfImagePreviewQueryJob()
  else if(command?.action==='textInsertsQuery')job=(await import('./text-inserts-job.mjs')).createPdfTextInsertsQueryJob()
  else if(['redactionsQuery','redactedCopy'].includes(command?.action))job=(await import('./redactions-job.mjs')).createPdfRedactionsJob(command.action)
  else if(['replacePages','insertPages'].includes(command?.action))job=(await import('./replace-pages-job.mjs')).createPdfReplacePagesJob()
  else if(command?.action==='editText')job=(await import('./text-edit-job.mjs')).createPdfTextEditJob()
  else if(command?.action==='annotateText')job=(await import('./annotation-job.mjs')).createPdfAnnotationJob()
  else if(command?.action==='deleteAnnotations')job=(await import('./annotation-delete-job.mjs')).createPdfAnnotationDeleteJob()
  else if(command?.action==='updateNotes')job=(await import('./note-update-job.mjs')).createPdfNoteUpdateJob()
  else if(command?.action==='pageOps')job=(await import('./page-ops-job.mjs')).createPdfPageOpsJob()
  else if(command?.action==='extractPages')job=(await import('./extract-pages-job.mjs')).createPdfExtractPagesJob()
  else if(command?.action==='splitPdf')job=(await import('./split-job.mjs')).createPdfSplitJob()
  else if(command?.action==='pageLayout')job=(await import('./page-layout-job.mjs')).createPdfPageLayoutJob()
  else if(command?.action==='formFields')job=(await import('./form-fields-job.mjs')).createPdfFormFieldsJob()
  else if(command?.action==='formValues')job=(await import('./form-values-job.mjs')).createPdfFormValuesJob()
  else if(command?.action==='textInserts')job=(await import('./text-inserts-job.mjs')).createPdfTextInsertsJob()
  else if(command?.action==='blockEdits')job=(await import('./block-edits-job.mjs')).createPdfBlockEditsJob()
  else if(command?.action==='blockMoves')job=(await import('./block-moves-job.mjs')).createPdfBlockMovesJob()
  else if(command?.action==='imageEdits')job=(await import('./image-edits-job.mjs')).createPdfImageEditsJob()
  else if(command?.action==='stamps')job=(await import('./stamps-job.mjs')).createPdfStampsJob()
  else if(command?.action==='imageBakes')job=(await import('./image-bakes-job.mjs')).createPdfImageBakesJob()
  else if(command?.action==='imageContent')job=(await import('./image-content-job.mjs')).createPdfImageContentJob()
  else if(command?.action==='imageQuery')job=(await import('./image-edits-job.mjs')).createPdfImageQueryJob()
  else throw Object.assign(new Error('INVALID_REQUEST'),{code:'INVALID_REQUEST'})
  const result=await job.execute(message?.input,message?.raw)
  process.send?.({result},()=>process.exit(0))
 }catch(error){process.send?.({error:typeof error?.code==='string'?error.code:'NATIVE_FAILED'},()=>process.exit(1))}
})
